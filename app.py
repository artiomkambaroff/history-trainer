ALL_Q = TERMS + METHOD

# Цвета
BG = "#f4f7fb"
FG = "#1f2d3d"
ACCENT = "#2f6fdd"
ACCENT_DARK = "#1f55b3"
GREEN_BG, GREEN_FG = "#d8f3dc", "#1b7a2f"
RED_BG, RED_FG = "#fde0e0", "#b3261e"
BTN_BG = "#ffffff"

F_TITLE = ("Segoe UI", 26, "bold")
F_HEAD = ("Segoe UI", 16, "bold")
F_TEXT = ("Segoe UI", 15)
F_BTN = ("Segoe UI", 15)
F_BIG = ("Segoe UI", 18, "bold")


def grade_for(percent):
    if percent >= 85:
        return 5, "отлично"
    if percent >= 70:
        return 4, "хорошо"
    if percent >= 50:
        return 3, "удовлетворительно"
    return 2, "неудовлетворительно"


class App(tk.Tk):
    def __init__(self):
        super().__init__()
        self.title("История России — тренажёр терминов и методологии")
        self.configure(bg=BG)
        self.geometry("1050x760")
        self.minsize(950, 700)

        self.mode_name = ""
        self.questions = []
        self.idx = 0
        self.score = 0
        self.answered = False
        self.mistakes = []
        self.current = None

        self.container = tk.Frame(self, bg=BG)
        self.container.pack(fill="both", expand=True, padx=30, pady=20)
        self.show_menu()

    # ------------------------------------------------------------------
    def clear(self):
        for w in self.container.winfo_children():
            w.destroy()

    def make_button(self, parent, text, command, bg=BTN_BG, fg=FG, **kw):
        b = tk.Button(parent, text=text, command=command, font=F_BTN, bg=bg, fg=fg,
                      activebackground="#e6eefc", activeforeground=FG, relief="groove",
                      bd=2, padx=14, pady=10, cursor="hand2", **kw)
        return b

    # ------------------------------------------------------------------
    def show_menu(self):
        self.clear()
        tk.Label(self.container, text="История России", font=F_TITLE, bg=BG, fg=ACCENT_DARK).pack(pady=(10, 0))
        tk.Label(self.container, text="Тренажёр научных терминов и методологии исследования",
                 font=F_HEAD, bg=BG, fg=FG).pack(pady=(4, 14))
        tk.Label(self.container,
                 text="Инструкция: выберите режим. В каждом вопросе нужно выбрать один верный вариант.\n"
                      "Ответ проверяется сразу: верный подсвечивается зелёным, ошибочный — красным.\n"
                      "За каждый верный ответ начисляется 1 балл. В конце выводится оценка.",
                 font=F_TEXT, bg=BG, fg=FG, justify="center").pack(pady=(0, 22))

        modes = [
            ("Тренажёр: научные термины  (%d вопросов)" % len(TERMS), "terms"),
            ("Тренажёр: методология исследования  (%d вопросов)" % len(METHOD), "method"),
            ("Итоговый тест с оценкой  (15 случайных вопросов)", "exam"),
        ]
        for text, key in modes:
            self.make_button(self.container, text, lambda k=key: self.start(k),
                             bg=ACCENT, fg="white").pack(fill="x", padx=60, pady=8)

        tk.Label(self.container,
                 text="Шкала оценок: 85–100% — «5»,  70–84% — «4»,  50–69% — «3»,  менее 50% — «2»",
                 font=("Segoe UI", 13), bg=BG, fg="#5b6b7c").pack(side="bottom", pady=10)

    # ------------------------------------------------------------------
    def start(self, mode):
        if mode == "terms":
            pool = list(TERMS)
            self.mode_name = "Тренажёр: научные термины"
        elif mode == "method":
            pool = list(METHOD)
            self.mode_name = "Тренажёр: методология исследования"
        else:
            pool = random.sample(ALL_Q, 15)
            self.mode_name = "Итоговый тест"
        random.shuffle(pool)
        self.questions = pool
        self.idx = 0
        self.score = 0
        self.mistakes = []
        self.show_question()

    def show_question(self):
        self.clear()
        self.answered = False
        q, opts, expl = self.questions[self.idx]
        correct = opts[0]
        shuffled = list(opts)
        random.shuffle(shuffled)
        self.current = (q, shuffled, correct, expl)

        top = tk.Frame(self.container, bg=BG)
        top.pack(fill="x")
        tk.Label(top, text=self.mode_name, font=F_HEAD, bg=BG, fg=ACCENT_DARK).pack(side="left")
        self.score_lbl = tk.Label(top, text="Баллы: %d" % self.score, font=F_HEAD, bg=BG, fg=FG)
        self.score_lbl.pack(side="right")
        tk.Label(self.container,
                 text="Выберите один верный ответ. Результат виден сразу после нажатия.",
                 font=("Segoe UI", 13), bg=BG, fg="#5b6b7c", anchor="w").pack(fill="x", pady=(2, 0))
        tk.Label(self.container,
                 text="Вопрос %d из %d" % (self.idx + 1, len(self.questions)),
                 font=F_TEXT, bg=BG, fg=FG, anchor="w").pack(fill="x", pady=(8, 4))

        tk.Label(self.container, text=q, font=F_BIG, bg=BG, fg=FG, wraplength=950,
                 justify="left", anchor="w").pack(fill="x", pady=(4, 14))

        self.buttons = []
        for i, text in enumerate(shuffled):
            b = tk.Button(self.container, text=text, font=F_BTN, bg=BTN_BG, fg=FG,
                          activebackground="#e6eefc", relief="groove", bd=2, padx=12, pady=9,
                          wraplength=900, justify="left", anchor="w", cursor="hand2",
                          command=lambda t=text, n=i: self.answer(n))
            b.pack(fill="x", pady=4)
            self.buttons.append(b)

        self.feedback = tk.Label(self.container, text="", font=F_TEXT, bg=BG, fg=FG,
                                 wraplength=950, justify="left", anchor="w")
        self.feedback.pack(fill="x", pady=(10, 4))

        bottom = tk.Frame(self.container, bg=BG)
        bottom.pack(side="bottom", fill="x", pady=(6, 0))
        self.make_button(bottom, "Начать заново", self.restart).pack(side="left")
        self.next_btn = self.make_button(bottom, "Далее →", self.next_question,
                                         bg=ACCENT, fg="white")
        self.next_btn.pack(side="right")
        self.next_btn.config(state="disabled")

    def answer(self, n):
        if self.answered:
            return
        self.answered = True
        q, shuffled, correct, expl = self.current
        chosen = shuffled[n]
        for i, b in enumerate(self.buttons):
            b.config(state="disabled", cursor="arrow")
            if shuffled[i] == correct:
                b.config(bg=GREEN_BG, disabledforeground=GREEN_FG)
        if chosen == correct:
            self.score += 1
            self.feedback.config(text="✔ Верно! " + expl, fg=GREEN_FG)
        else:
            self.buttons[n].config(bg=RED_BG, disabledforeground=RED_FG)
            self.mistakes.append((q, chosen, correct))
            self.feedback.config(text="✘ Неверно. Правильный ответ выделен зелёным. " + expl, fg=RED_FG)
        self.score_lbl.config(text="Баллы: %d" % self.score)
        last = self.idx == len(self.questions) - 1
        self.next_btn.config(state="normal", text="Показать результат" if last else "Далее →")

    def next_question(self):
        if not self.answered:
            return
        self.idx += 1
        if self.idx >= len(self.questions):
            self.show_result()
        else:
            self.show_question()

    def restart(self):
        if messagebox.askyesno("Начать заново", "Вернуться в меню? Текущий результат будет сброшен."):
            self.show_menu()

    # ------------------------------------------------------------------
    def show_result(self):
        self.clear()
        total = len(self.questions)
        percent = round(self.score * 100 / total)
        mark, word = grade_for(percent)
        color = GREEN_FG if mark >= 4 else (ACCENT_DARK if mark == 3 else RED_FG)

        tk.Label(self.container, text="Результат", font=F_TITLE, bg=BG, fg=ACCENT_DARK).pack(pady=(6, 2))
        tk.Label(self.container, text=self.mode_name, font=F_HEAD, bg=BG, fg=FG).pack()
        tk.Label(self.container, text="Баллы: %d из %d  (%d%%)" % (self.score, total, percent),
                 font=F_BIG, bg=BG, fg=FG).pack(pady=(14, 4))
        tk.Label(self.container, text="Оценка: %d (%s)" % (mark, word),
                 font=("Segoe UI", 24, "bold"), bg=BG, fg=color).pack(pady=(0, 10))

        if self.mistakes:
            tk.Label(self.container, text="Работа над ошибками:", font=F_HEAD, bg=BG, fg=FG,
                     anchor="w").pack(fill="x")
            frame = tk.Frame(self.container, bg=BG)
            frame.pack(fill="both", expand=True, pady=4)
            sb = tk.Scrollbar(frame)
            sb.pack(side="right", fill="y")
            txt = tk.Text(frame, font=("Segoe UI", 13), wrap="word", bg="white", fg=FG,
                          yscrollcommand=sb.set, height=10, relief="groove", bd=2)
            txt.pack(side="left", fill="both", expand=True)
            sb.config(command=txt.yview)
            txt.tag_configure("q", font=("Segoe UI", 13, "bold"))
            txt.tag_configure("bad", foreground=RED_FG)
            txt.tag_configure("good", foreground=GREEN_FG)
            for i, (q, chosen, correct) in enumerate(self.mistakes, 1):
                txt.insert("end", "%d. %s\n" % (i, q), "q")
                txt.insert("end", "   Ваш ответ: %s\n" % chosen, "bad")
                txt.insert("end", "   Верный ответ: %s\n\n" % correct, "good")
            txt.config(state="disabled")
        else:
            tk.Label(self.container, text="Ошибок нет — отличная работа!", font=F_HEAD,
                     bg=BG, fg=GREEN_FG).pack(pady=20)

        bottom = tk.Frame(self.container, bg=BG)
        bottom.pack(side="bottom", fill="x", pady=(8, 0))
        self.make_button(bottom, "Начать заново", self.show_menu, bg=ACCENT, fg="white").pack(side="left")
        self.make_button(bottom, "Выход", self.destroy).pack(side="right")


